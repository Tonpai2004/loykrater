// Swap a stock couplet to the same verse in the active language; custom wishes pass through untouched
export function localizeWish(text: string, locale: Locale): string {
  const other: Locale = locale === 'th' ? 'en' : 'th';
  const idx = BILINGUAL_WISH_COUPLETS[other].indexOf(text);
  return idx >= 0 ? BILINGUAL_WISH_COUPLETS[locale][idx] : text;
}
